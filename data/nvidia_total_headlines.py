import re
import time
import requests
import pandas as pd
from getpass import getpass

# ---------------- SETTINGS (edit these) ----------------
API_KEY = ""                      # paste your key here, or leave empty to be asked when you run
TICKER = "NVDA"
START_DATE = "2022-10-20"         # YYYY-MM-DD
END_DATE = "2026-10-20"           # YYYY-MM-DD
# A headline is kept if it contains ANY of these (OR logic).
# A trailing * means "starts with", e.g. "invest*" matches invest, investor, investment, investing.
# Without *, the word must match exactly (so "AI" will not match "said").
KEYWORDS = [
    "stock*", "share", "shares", "shareholder*", "earnings", "revenue*", "profit*",
    "financ*", "invest*", "price target", "analyst*", "upgrade*", "downgrade*",
    "rally", "surge*", "plunge*", "sell-off", "selloff", "dividend*", "buyback*",
    "market cap", "valuation", "guidance", "forecast*", "quarter*", "Q1", "Q2", "Q3", "Q4",
    "Wall Street", "Nasdaq", "S&P 500", "trading", "bullish", "bearish", "IPO", "EPS",
]
SEARCH_DESCRIPTION = True         # also search the article description, not just the title
SLEEP_BETWEEN_CALLS = 0           # set to 12 if you are on a free plan (5 calls/min limit)
OUTPUT_CSV = "nvda_headlines.csv"
# --------------------------------------------------------

if not API_KEY.strip():
    API_KEY = getpass("Paste your Massive/Polygon API key (input is hidden): ")
API_KEY = API_KEY.strip()

# The company rebranded from Polygon.io to Massive; try both domains.
BASE_URLS = ["https://api.massive.com", "https://api.polygon.io"]
ENDPOINT = "/v2/reference/news"


def get_json(url, params, max_retries=6):
    """GET with retry on rate limit (429) and temporary server errors."""
    for attempt in range(max_retries):
        r = requests.get(url, params=params, timeout=60)
        if r.status_code == 429 or r.status_code >= 500:
            wait = 15 * (attempt + 1)
            print(f"  status {r.status_code}, waiting {wait}s then retrying...")
            time.sleep(wait)
            continue
        if r.status_code != 200:
            raise RuntimeError(f"HTTP {r.status_code} from {url}\nResponse: {r.text[:500]}")
        return r.json()
    raise RuntimeError("Too many retries - rate limit or server problem.")


def fetch_news(base_url):
    params = {
        "ticker": TICKER,
        "published_utc.gte": START_DATE,
        "published_utc.lte": END_DATE,
        "order": "asc",
        "sort": "published_utc",
        "limit": 1000,
        "apiKey": API_KEY,
    }
    url = base_url + ENDPOINT
    articles, page = [], 0
    while url:
        data = get_json(url, params)
        results = data.get("results", [])
        articles.extend(results)
        page += 1
        last = results[-1].get("published_utc", "")[:10] if results else "-"
        print(f"Page {page}: +{len(results)} articles (total {len(articles)}), reached {last}")
        url = data.get("next_url")
        params = {"apiKey": API_KEY}          # next_url already holds the other filters
        if url and SLEEP_BETWEEN_CALLS:
            time.sleep(SLEEP_BETWEEN_CALLS)
    return articles


# ---------- download (tries each domain until one works) ----------
articles, last_error = None, None
for base in BASE_URLS:
    try:
        print(f"Trying {base} ...")
        articles = fetch_news(base)
        break
    except Exception as e:
        last_error = e
        print(f"Failed on {base}: {e}\n")

if articles is None:
    raise SystemExit(f"Could not fetch data. Last error:\n{last_error}")

print(f"\nDownloaded {len(articles)} articles in total.")

# ---------- build dataframe ----------
rows = []
for a in articles:
    rows.append({
        "published_utc": a.get("published_utc"),
        "title": a.get("title") or "",
        "description": a.get("description") or "",
        "publisher": (a.get("publisher") or {}).get("name"),
        "url": a.get("article_url"),
    })
df = pd.DataFrame(rows)

if df.empty:
    raise SystemExit("API returned no articles for this ticker/date range. Check your plan's data access.")

df["published_utc"] = pd.to_datetime(df["published_utc"], utc=True)
df["date"] = df["published_utc"].dt.date
df = df.drop_duplicates(subset=["title", "published_utc"]).reset_index(drop=True)

# ---------- keyword filter (whole-word, case-insensitive) ----------
def make_pattern(k):
    if k.endswith("*"):                                   # prefix match: invest* -> investor, investment...
        return re.compile(r"\b" + re.escape(k[:-1]) + r"\w*", re.IGNORECASE)
    return re.compile(r"(?<!\w)" + re.escape(k) + r"(?!\w)", re.IGNORECASE)   # whole word / phrase


patterns = {k: make_pattern(k) for k in KEYWORDS}


def matched(row):
    text = row["title"] + (" " + row["description"] if SEARCH_DESCRIPTION else "")
    return ", ".join(k for k, p in patterns.items() if p.search(text))


df["matched_keywords"] = df.apply(matched, axis=1)
filtered = df[df["matched_keywords"] != ""].reset_index(drop=True)

print(f"Headlines matching {KEYWORDS}: {len(filtered)} of {len(df)}")

result = filtered[["date", "published_utc", "title", "matched_keywords", "publisher", "url"]]
result.to_csv(OUTPUT_CSV, index=False)
print(f"Saved to {OUTPUT_CSV} (see the Files panel on the left in Colab)")

pd.set_option("display.max_colwidth", 120)
display(result[["date", "title", "matched_keywords"]].head(30))

