import pandas as pd
import numpy as np
import torch
import matplotlib.pyplot as plt
import seaborn as sns

from google.colab import files
from transformers import AutoTokenizer, AutoModelForSequenceClassification
from tqdm.auto import tqdm

# Upload NVIDIA_NVDA_Finance_Headlines_Filtered.xlsx
uploaded = files.upload()
file_path = next(iter(uploaded.keys()))

# Load the actual headlines worksheet (second sheet)
df = pd.read_excel(
    file_path,
    sheet_name="Filtered Headlines"
)

# Check required columns
required_columns = ["title", "published_utc"]
missing = [c for c in required_columns if c not in df.columns]

if missing:
    raise ValueError(f"Missing required columns: {missing}")

# Clean and prepare the data
df["title"] = df["title"].fillna("").astype(str).str.strip()
df["published_utc"] = pd.to_datetime(
    df["published_utc"], errors="coerce", utc=True
)

df = df[
    df["title"].ne("") & df["published_utc"].notna()
].copy()

df = df.reset_index(drop=True)
df["date"] = df["published_utc"].dt.floor("D")

print("Headlines ready for analysis:", len(df))
print(df[["published_utc", "title"]].head())

MODEL_NAME = "ProsusAI/finbert"

device = torch.device(
    "cuda" if torch.cuda.is_available() else "cpu"
)

print("Running on:", device)

tokenizer = AutoTokenizer.from_pretrained(MODEL_NAME)

model = AutoModelForSequenceClassification.from_pretrained(
    MODEL_NAME
).to(device)

model.eval()

# Get the sentiment labels in the model's correct order
id2label = {
    int(k): v.lower()
    for k, v in model.config.id2label.items()
}

print("FinBERT labels:", id2label)

texts = df["title"].tolist()

positive_scores = []
negative_scores = []
neutral_scores = []

batch_size = 32

for start in tqdm(range(0, len(texts), batch_size)):
    batch = texts[start:start + batch_size]

    inputs = tokenizer(
        batch,
        padding=True,
        truncation=True,
        max_length=128,
        return_tensors="pt"
    ).to(device)

    with torch.inference_mode():
        logits = model(**inputs).logits
        probabilities = torch.softmax(logits, dim=-1).cpu().numpy()

    for probs in probabilities:
        scores = {
            id2label[i]: float(probs[i])
            for i in range(len(probs))
        }

        positive_scores.append(scores["positive"])
        negative_scores.append(scores["negative"])
        neutral_scores.append(scores["neutral"])

# Store the scores for every headline
df["positive_score"] = positive_scores
df["negative_score"] = negative_scores
df["neutral_score"] = neutral_scores

# Assign the highest-probability sentiment label
score_columns = [
    "positive_score",
    "negative_score",
    "neutral_score"
]

df["sentiment"] = (
    df[score_columns]
    .idxmax(axis=1)
    .str.replace("_score", "", regex=False)
)

# Continuous sentiment score: range approximately -1 to +1
df["sentiment_score"] = (
    df["positive_score"] - df["negative_score"]
)

print("\nSentiment classification complete.")
print(df["sentiment"].value_counts())

# Aggregate daily sentiment
daily = (
    df.groupby("date")
    .agg(
        average_sentiment=("sentiment_score", "mean"),
        positive_probability=("positive_score", "mean"),
        negative_probability=("negative_score", "mean"),
        neutral_probability=("neutral_score", "mean"),
        headline_count=("title", "count")
    )
    .sort_index()
)

# Rolling average across 7 calendar days
daily["rolling_7d"] = (
    daily["average_sentiment"]
    .rolling("7D", min_periods=1)
    .mean()
)

# Plot 1: Sentiment score versus time
fig, ax = plt.subplots(figsize=(15, 6))

ax.plot(
    daily.index,
    daily["average_sentiment"],
    alpha=0.45,
    linewidth=1,
    label="Daily average sentiment"
)

ax.plot(
    daily.index,
    daily["rolling_7d"],
    linewidth=2,
    label="7-day rolling average"
)

ax.axhline(0, linestyle="--", linewidth=1)

ax.set_title("NVIDIA (NVDA) Financial News Sentiment Over Time")
ax.set_xlabel("Publication date")
ax.set_ylabel("Sentiment score (positive − negative)")
ax.legend()
ax.grid(alpha=0.25)

plt.tight_layout()
plt.savefig("NVDA_sentiment_vs_time.png", dpi=300)
plt.show()


# Plot 2: Daily headline volume
fig, ax = plt.subplots(figsize=(15, 4))

ax.bar(
    daily.index,
    daily["headline_count"],
    width=1.0
)

ax.set_title("Daily Volume of NVIDIA Financial Headlines")
ax.set_xlabel("Publication date")
ax.set_ylabel("Number of headlines")
ax.grid(axis="y", alpha=0.25)

plt.tight_layout()
plt.savefig("NVDA_headline_volume.png", dpi=300)
plt.show()

import os
