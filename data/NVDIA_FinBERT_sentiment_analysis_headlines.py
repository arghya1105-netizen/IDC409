# 1. Check that the sentiment analysis data exists
if "df" not in globals():
    raise ValueError("Run the FinBERT analysis cell first.")

# 2. Create a copy so the original analysis data remains unchanged
df_export = df.copy()

# 3. Remove timezone information from datetime columns
for col in df_export.columns:
    if isinstance(df_export[col].dtype, pd.DatetimeTZDtype):
        df_export[col] = df_export[col].dt.tz_localize(None)

# Also handle any object columns containing timezone-aware timestamps
for col in df_export.select_dtypes(include=["object"]).columns:
    df_export[col] = df_export[col].map(
        lambda x: x.tz_localize(None)
        if isinstance(x, pd.Timestamp) and x.tzinfo is not None
        else x
    )

# 4. Create the daily sentiment summary
df_export["date"] = pd.to_datetime(
    df_export["published_utc"], errors="coerce", utc=True
).dt.floor("D").dt.tz_localize(None)

daily = (
    df_export.dropna(subset=["date"])
    .groupby("date")
    .agg(
        average_sentiment=("sentiment_score", "mean"),
        positive_probability=("positive_score", "mean"),
        negative_probability=("negative_score", "mean"),
        neutral_probability=("neutral_score", "mean"),
        headline_count=("title", "count")
    )
    .sort_index()
)

daily["rolling_7d"] = (
    daily["average_sentiment"]
    .rolling("7D", min_periods=1)
    .mean()
)

# 5. Create sentiment distribution
sentiment_summary = (
    df_export["sentiment"]
    .value_counts()
    .rename_axis("sentiment")
    .reset_index(name="headline_count")
)

sentiment_summary["percentage"] = (
    sentiment_summary["headline_count"]
    / len(df_export) * 100
).round(2)

# 6. Export everything to Excel
output_file = "/content/NVDA_FinBERT_Sentiment_Analysis.xlsx"

with pd.ExcelWriter(output_file, engine="openpyxl") as writer:
    df_export.to_excel(
        writer, sheet_name="Headline Sentiment", index=False
    )
    daily.to_excel(
        writer, sheet_name="Daily Sentiment"
    )
    sentiment_summary.to_excel(
        writer, sheet_name="Sentiment Distribution", index=False
    )

print("Excel workbook created successfully!")
print("Headlines analysed:", len(df_export))
print("Daily records:", len(daily))
print("Saved to:", output_file)

# 7. Download the workbook
files.download(output_file)